import { useMutation, useQueryClient } from '@tanstack/react-query'
import { useState } from 'react'
import { useTranslation } from 'react-i18next'

import { Alert, AlertDescription } from '@/components/ui/alert'
import { Button } from '@/components/ui/button'
import { Field, FieldDescription, FieldLabel } from '@/components/ui/field'
import { Input } from '@/components/ui/input'
import { getServerErrorMessage } from '@/lib/server-error-message'

import { currentReleaseIdentity } from '../access'
import { acceptRelease } from '../api'
import type { AcceptanceEnvelope, Release } from '../types'

type Props = {
  identity: string
  release: Release
  canAccept: boolean
  busy: boolean
  onBusy: (busy: boolean) => void
}

export function ReleaseAcceptance(props: Props) {
  const { t } = useTranslation()
  const queryClient = useQueryClient()
  const [file, setFile] = useState<File | null>(null)
  const mutation = useMutation({
    mutationFn: async (selected: File) => {
      props.onBusy(true)
      if (selected.size > 128 * 1024) {
        throw new Error(
          t('Acceptance evidence must be a JSON file no larger than 128 KiB.')
        )
      }
      let evidence: unknown
      try {
        evidence = JSON.parse(await selected.text())
      } catch {
        throw new Error(
          t('Acceptance evidence must contain a signed payload and signature.')
        )
      }
      if (
        !evidence ||
        typeof evidence !== 'object' ||
        !('payload' in evidence) ||
        !('signature' in evidence) ||
        typeof evidence.payload !== 'string' ||
        typeof evidence.signature !== 'string' ||
        !evidence.payload ||
        !evidence.signature
      ) {
        throw new Error(
          t('Acceptance evidence must contain a signed payload and signature.')
        )
      }
      return acceptRelease(
        props.release.id,
        props.release.revision,
        evidence as AcceptanceEnvelope
      )
    },
    retry: false,
    meta: { errorToast: false },
    onSuccess: () => {
      if (currentReleaseIdentity() === props.identity) setFile(null)
    },
    onSettled: async () => {
      if (currentReleaseIdentity() !== props.identity) return
      await queryClient.invalidateQueries({
        queryKey: ['bellobuddy-release', props.identity, props.release.id],
      })
      props.onBusy(false)
    },
  })
  return (
    <section className='space-y-3'>
      <h2 className='font-semibold'>{t('Windows acceptance evidence')}</h2>
      <p className='text-muted-foreground text-sm'>
        {t(
          'Formal publication requires evidence signed by a trusted Windows acceptance machine. Uploading a build manifest alone does not approve a release.'
        )}
      </p>
      {props.canAccept &&
        props.release.state === 'ready' &&
        !props.release.disabled && (
          <>
            <Field>
              <FieldLabel htmlFor='release-evidence'>
                {t('Signed acceptance evidence file')}
              </FieldLabel>
              <Input
                id='release-evidence'
                type='file'
                accept='.json,application/json'
                disabled={props.busy}
                onChange={(event) => {
                  setFile(event.target.files?.[0] ?? null)
                  event.target.value = ''
                }}
              />
              <FieldDescription>
                {file?.name ||
                  t(
                    'Select the JSON evidence generated by the trusted acceptance machine.'
                  )}
              </FieldDescription>
            </Field>
            <Button
              variant='outline'
              disabled={!file || props.busy}
              onClick={() => {
                if (file) mutation.mutate(file)
              }}
            >
              {mutation.isPending
                ? t('Verifying evidence...')
                : t('Verify acceptance evidence')}
            </Button>
          </>
        )}
      {mutation.isError && (
        <Alert variant='destructive'>
          <AlertDescription>
            {getServerErrorMessage(mutation.error)}
          </AlertDescription>
        </Alert>
      )}
    </section>
  )
}
